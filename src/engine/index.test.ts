/**
 * index.test.ts — Table-driven scenario test for analyseDag + timing
 * Tests written BEFORE implementation per AGENTS.md §3 rule 5.
 *
 * Reads scenarios.json and asserts each dag gives the expected verdict.
 * Dag 106 (UNDER_DECLARED) is it.todo — P1-T09 will enable it.
 */

import { describe, expect, it } from 'vitest';
import { readFileSync } from 'fs';
import { join } from 'path';
import type { DemoData, Scenario } from './types';
import { analyseDag } from './index';

// ---------------------------------------------------------------------------
// Load demo data once (from public/data/*.json — generated by P1-T02)
// ---------------------------------------------------------------------------

function loadDemoData(): DemoData {
  const base = join(process.cwd(), 'public', 'data');
  const mouza = JSON.parse(readFileSync(join(base, 'mouza.json'), 'utf-8'));
  const dags = JSON.parse(readFileSync(join(base, 'dags.geojson'), 'utf-8'));
  const people = JSON.parse(readFileSync(join(base, 'people.json'), 'utf-8'));
  const events = JSON.parse(readFileSync(join(base, 'events.json'), 'utf-8'));
  const scenarios = JSON.parse(readFileSync(join(base, 'scenarios.json'), 'utf-8'));
  const feeRules = JSON.parse(readFileSync(join(base, 'feeRules.json'), 'utf-8'));
  return { mouza, dags, people, events, scenarios, feeRules };
}

let data: DemoData;
let scenarios: Scenario[];

try {
  data = loadDemoData();
  scenarios = data.scenarios;
} catch {
  // If data files are missing (e.g. test environment before npm run data), skip gracefully
  data = null as unknown as DemoData;
  scenarios = [];
}

// ---------------------------------------------------------------------------
// Scenario table-driven tests
// ---------------------------------------------------------------------------

describe('analyseDag — scenario verdict tests', () => {
  if (!data) {
    it.todo('public/data/*.json not generated yet — run npm run data');
    return;
  }

  for (const scenario of scenarios) {
    it(`dag ${scenario.dagId} (${scenario.key}) → ${scenario.expected}`, () => {
      const result = analyseDag(scenario.dagId, data);
      expect(result.verdict).toBe(scenario.expected);

      // Check that the expected issue code is present for non-green scenarios
      if (scenario.expected !== 'green') {
        const found = result.issues.some((i) => i.code === scenario.key);
        expect(found, `expected issue code ${scenario.key} in dag ${scenario.dagId}`).toBe(true);
      }
    });
  }
});

// ---------------------------------------------------------------------------
// All non-scenario dags must be green
// ---------------------------------------------------------------------------

describe('analyseDag — all non-scenario dags are green', () => {
  if (!data) {
    it.todo('public/data/*.json not generated yet — run npm run data');
    return;
  }

  const scenarioDagIds = new Set(scenarios.map((s) => s.dagId));
  const allDagIds = data.dags.features.map((f) => f.properties.id);
  const nonScenarioDags = allDagIds.filter((id) => !scenarioDagIds.has(id));

  for (const dagId of nonScenarioDags) {
    it(`dag ${dagId} is green`, () => {
      const result = analyseDag(dagId, data);
      expect(result.verdict).toBe('green');
    });
  }
});

// ---------------------------------------------------------------------------
// Performance: analyseDag must run in < 20 ms per dag
// ---------------------------------------------------------------------------

describe('analyseDag — performance', () => {
  if (!data) {
    it.todo('public/data/*.json not generated yet — run npm run data');
    return;
  }

  it('runs each dag in under 20 ms (loose bound)', () => {
    const allDagIds = data.dags.features.map((f) => f.properties.id);
    for (const dagId of allDagIds) {
      const start = performance.now();
      analyseDag(dagId, data);
      const elapsed = performance.now() - start;
      expect(elapsed, `dag ${dagId} took ${elapsed.toFixed(1)} ms`).toBeLessThan(20);
    }
  });

  it('memoized calls are faster (near-zero) on the second call', () => {
    const dagId = '101';
    // First call — uncached
    analyseDag(dagId, data);
    // Second call — should be from memo
    const start = performance.now();
    analyseDag(dagId, data);
    const elapsed = performance.now() - start;
    expect(elapsed).toBeLessThan(1);
  });
});
